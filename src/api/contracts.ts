import type { PlayerOptions } from '@/game/config/options'
import type { EndReason } from '@/game/match/match'

/**
 * The REST contracts of the ranking and match history API, shared by the
 * client and the MSW handlers.
 */

/**
 * The configuration a match was played with. Only the two options the player
 * can change vary between matches; every other balancing number is fixed by
 * the build, so these two are what the ranking compares by.
 */
export type MatchConfig = PlayerOptions

/** One completed match — a history entry and, at the same time, a ranking entry. */
export interface MatchRecord {
  /** Generated by the client when the match ends, so a resend is recognisable. */
  matchId: string
  playerId: string
  playerName: string
  /** ISO date the match ended. */
  endedAt: string
  score: number
  /** Active play time in seconds, excluding pauses. */
  durationSeconds: number
  endReason: EndReason
  config: MatchConfig
}

export interface RankingEntry extends MatchRecord {
  /** 1-based position among the matches played with the same config. */
  rank: number
}

export interface PageQuery {
  /** 1-based. */
  page: number
  pageSize: number
}

export interface Page<T> {
  items: T[]
  page: number
  pageSize: number
  totalItems: number
  totalPages: number
  /**
   * The data revision the page was read at. Every registered match raises it,
   * so of two responses for the same query the one with the lower revision is
   * older, whatever order they arrive in.
   */
  revision: number
}

export interface ApiError {
  message: string
}

export const PAGE_SIZE = 5
export const MAX_PAGE_SIZE = 50

const isRecord = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null

const isCount = (value: unknown): value is number => Number.isInteger(value) && (value as number) >= 0

export function isMatchConfig(value: unknown): value is MatchConfig {
  return isRecord(value) && typeof value.sessionSeconds === 'number' && typeof value.spawnIntervalSeconds === 'number'
}

export function isMatchRecord(value: unknown): value is MatchRecord {
  return (
    isRecord(value) &&
    typeof value.matchId === 'string' &&
    value.matchId !== '' &&
    typeof value.playerId === 'string' &&
    value.playerId !== '' &&
    typeof value.playerName === 'string' &&
    typeof value.endedAt === 'string' &&
    !Number.isNaN(Date.parse(value.endedAt)) &&
    isCount(value.score) &&
    typeof value.durationSeconds === 'number' &&
    value.durationSeconds >= 0 &&
    (value.endReason === 'time-up' || value.endReason === 'destroyed') &&
    isMatchConfig(value.config)
  )
}

export function isRankingEntry(value: unknown): value is RankingEntry {
  return isMatchRecord(value) && Number.isInteger((value as Partial<RankingEntry>).rank)
}

export function isPage<T>(value: unknown, isItem: (item: unknown) => item is T): value is Page<T> {
  return (
    isRecord(value) &&
    Array.isArray(value.items) &&
    value.items.every(isItem) &&
    isCount(value.page) &&
    isCount(value.pageSize) &&
    isCount(value.totalItems) &&
    isCount(value.totalPages) &&
    isCount(value.revision)
  )
}
